<h4>Установка астрологического календаря на мобильный телефон</h4>
Астрологический календарь <b>ASTROMAXIMUM</b> может быть установлен на любой телефон,
имеющий поддержку Java-приложений. Из-за отсутствия единых стандартов у производителей
мобильных телефонов мы не гарантируем, что календарь будет работать на конкретной модели телефона.
Поэтому на нашем сайте Вы можете найти бесплатную демо-версию
с событиями прошлого года, с помощью которой можно опробовать процесс установки и получить представление о возможностях
<b>ASTROMAXIMUM</b>.</p>
<p>Для загрузки календаря или городов необходимо произвести вход на сайт через форму слева.
Если Вы не являетесь зарегистрированным пользователем, используйте ограниченный демо-аккаунт
(логин: 123456789 пароль: 012345678 ). В этом случае доступны не все страницы сайта.</p>


<p>Календарь может быть установлен на мобильный телефон различными способами в зависимости 
от модели телефона. Рекомендуется прочитать инструкцию к телефону (раздел, касающийся установки
Java-игр или Java-приложений), чтобы выбрать наиболее удобный для Вас способ инсталляции.</p> 
<ol>
<li>Установка через интернет соединение телефона</li>
<p>Наиболее простой способ, если на Вашем телефоне активирована услуга "Интернет". 
По вопросам настройки доступа к Интернет обращайтесь к Вашему мобильному оператору. 
Адрес мобильной версии нашего сайта - 
<a href="http://astromaximum.mobi/">http://astromaximum.mobi/</a></p>
<li>Установка с помощью компьютера</li>
<p>Перед началом установки следует определиться со способом подключения телефона к компьютеру:
USB кабель, соединение через инфракрасный порт или Bluetooth. Некоторые марки телефонов
могут потребовать установки драйверов и специальных приложений, например: Nokia - Nokia PC Suite
(Java приложения устанавливаются напрямую),
Samsung - Samsung PC Studio и т.п. Убедитесь, что у Вас установлены свежие версии этих приложений.
</p>
<p>На странице загрузки демо-версии следует указать адрес электронной почты, на который
будут высланы ссылки для скачивания.</p>
<p class="alert">Проверьте дату на телефоне. В случае неправильной даты корректная работа календаря не
гарантируется.</a>
<p>
Дистрибутив астрологического календаря состоит из 2 файлов - собственно архива с календарем (JAR файл)
и дескриптора приложения (JAD файл). Сохраните оба файла одну папку, а затем перенесите
их на мобильный телефон, подключив его к компьютеру. В зависимости от модели телефона и способа
соединения файлы могут оказаться в почтовых сообщениях, папках "Принятые файлы", "Другие файлы" и т.п.
Запустите установку, выбрав JAD или JAR файл (зависит от модели телефона). Если установка прошла успешно,
запустите календарь.
</p>
<p class="alert">Корректная работа календаря не гарантируется, если между скачиванием дистрибутива
и первым запуском календаря прошло более 12 часов.</p>
